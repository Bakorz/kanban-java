import { readFileSync } from 'node:fs';
import { expect, test } from '@playwright/test';

const enabled = process.env.KANBAN_E2E_REAL_CRUD === '1';

test('real Java and PostgreSQL board/card lifecycle through browser', async ({ page }, testInfo) => {
  test.skip(!enabled, 'Run with the isolated backend fixture and KANBAN_E2E_REAL_CRUD=1.');
  const session = JSON.parse(readFileSync(new URL('../../backend/target/e2e-session.json', import.meta.url), 'utf8'));
  await page.route('https://auth.kanban.test/**', (route) => {
    const path = new URL(route.request().url()).pathname;
    if (path.endsWith('/token')) return route.fulfill({ json: session });
    if (path.endsWith('/user')) return route.fulfill({ json: session.user });
    if (path.endsWith('/logout')) return route.fulfill({ status: 204 });
    return route.fulfill({ status: 400, json: { message: 'Unexpected isolated auth fixture request' } });
  });
  // No /api routes are intercepted: browser -> Vite proxy -> Java -> local PostgreSQL.
  const name = `Browser ${testInfo.project.name} ${Date.now()}`;
  await page.goto('/login');
  await page.getByLabel('Email (required)').fill(session.user.email);
  await page.getByLabel('Password (required)').fill('fixture-only-password');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'My boards', level: 1 })).toBeVisible();
  await page.getByRole('button', { name: 'New board' }).click();
  await page.getByLabel('Board name (required)').fill(name);
  await page.getByRole('button', { name: 'Create board', exact: true }).click();
  await page.getByRole('link', { name, exact: true }).click();
  await expect(page.getByRole('heading', { name, level: 1 })).toBeVisible();
  await page.getByRole('button', { name: 'Add card to To Do' }).click();
  await page.getByLabel('Title (required)').fill('Persisted task');
  await page.getByLabel(/Description \(optional/).fill('Saved by Java to PostgreSQL');
  await page.getByLabel('Due date (optional)').fill('2027-03-04');
  await page.getByLabel('Priority', { exact: true }).selectOption('HIGH');
  await page.getByRole('button', { name: 'Create card', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Card created.');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Persisted task', exact: true })).toBeVisible();
  await expect(page.getByText('Saved by Java to PostgreSQL', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit card Persisted task' }).click();
  await page.getByLabel(/Description \(optional/).fill('');
  await page.getByLabel('Due date (optional)').fill('');
  await page.getByRole('button', { name: 'Save card' }).click();
  await expect(page.getByRole('status')).toHaveText('Card updated.');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Persisted task', exact: true })).toBeVisible();
  await expect(page.getByText('Saved by Java to PostgreSQL', { exact: true })).toHaveCount(0);
  await expect(page.locator('time')).toHaveCount(0);
  await page.getByLabel('Move to column').selectOption({ label: 'In Progress' });
  await page.getByRole('button', { name: 'Move Persisted task to selected column' }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('status')).toHaveText('Card moved.');
  await page.reload();
  const inProgress = page.locator('.column').filter({ has: page.getByRole('heading', { name: /^In Progress/ }) });
  await expect(inProgress.getByRole('heading', { name: 'Persisted task', exact: true })).toBeVisible();
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.locator('body').evaluate((el) => el.clientWidth));
  await page.screenshot({ path: `.tools/screenshots/real-workspace-${testInfo.project.name}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Delete card Persisted task' }).click();
  await page.getByRole('button', { name: 'Confirm delete' }).click();
  await expect(page.getByRole('status')).toHaveText('Card deleted.');
  await page.getByRole('button', { name: 'Edit board', exact: true }).click();
  await page.getByLabel('Board name (required)').fill(`${name} renamed`);
  await page.getByRole('button', { name: 'Save board' }).click();
  await expect(page.getByRole('heading', { name: `${name} renamed`, level: 1 })).toBeVisible();
  await page.getByRole('button', { name: 'Delete board', exact: true }).click();
  await expect(page.getByText(/All columns and cards in this board will also be deleted/)).toBeVisible();
  await page.getByRole('button', { name: 'Confirm delete' }).click();
  await expect(page.getByRole('heading', { name: 'My boards', level: 1 })).toBeVisible();
  await expect(page.getByRole('link', { name: `${name} renamed`, exact: true })).toHaveCount(0);
});
